import AppKit

/// Notices text the user copies in any app, and adds it to the clipboard history.
final class ClipboardWatcher {
    private let history: ClipboardHistory
    private var timer: Timer?
    private var changeCount = NSPasteboard.general.changeCount

    /// Types that password managers and similar apps add to a copy that should not be remembered.
    /// See nspasteboard.org.
    private static let privateTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword"),
    ]
    /// Types that mark a copy of files or folders, such as one made in Finder.
    private static let fileTypes: Set<NSPasteboard.PasteboardType> = [
        .fileURL, .init("NSFilenamesPboardType"),
    ]

    init(history: ClipboardHistory) {
        self.history = history
    }

    func start() {
        guard timer == nil else { return }
        // Whatever is on the clipboard already was copied at some unknown time, so it is left out.
        changeCount = NSPasteboard.general.changeCount
        // The pasteboard announces no changes, so look at it twice a second. That costs next to nothing.
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        timer.tolerance = 0.2
        // The common modes keep it running while a menu is open.
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func check() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount

        guard Preferences.keepsHistory,
              let text = Self.text(
                  in: pasteboard, includingPrivate: Preferences.savesPrivateCopies,
                  includingFileLocations: Preferences.savesFileLocations)
        else { return }
        history.add(text)
    }

    /// The text to keep from the copy on `pasteboard`, or nil if there is none. A copy of files or folders gives
    /// their locations, one per line, with `includingFileLocations`, and nothing without. A copy marked private
    /// gives nothing unless `includingPrivate`.
    static func text(in pasteboard: NSPasteboard, includingPrivate: Bool, includingFileLocations: Bool) -> String? {
        let types = Set(pasteboard.types ?? [])
        guard includingPrivate || types.isDisjoint(with: privateTypes) else { return nil }
        // Copying files or folders also puts their names on the clipboard as text. The user copied the files, not
        // their names, so the names are never kept.
        guard types.isDisjoint(with: fileTypes) else {
            guard includingFileLocations else { return nil }
            let paths = fileLocations(in: pasteboard)
            return paths.isEmpty ? nil : paths.joined(separator: "\n")
        }
        return pasteboard.string(forType: .string)
    }

    /// The paths of the files and folders copied onto `pasteboard`.
    private static func fileLocations(in pasteboard: NSPasteboard) -> [String] {
        let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true])
        if let urls = urls as? [URL], !urls.isEmpty {
            return urls.map(\.path)
        }
        // Some apps still copy files only under the type older versions of macOS used.
        return pasteboard.propertyList(forType: .init("NSFilenamesPboardType")) as? [String] ?? []
    }
}
