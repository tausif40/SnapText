import AppKit

/// Notices text the user copies in any app, and adds it to the clipboard history.
final class ClipboardWatcher {
    private let history: ClipboardHistory
    private var timer: Timer?
    private var changeCount = NSPasteboard.general.changeCount

    /// Types that password managers and similar apps add to a copy that should not be remembered.
    /// See nspasteboard.org.
    private static let privateTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword"),
    ]

    init(history: ClipboardHistory) {
        self.history = history
    }

    func start() {
        guard timer == nil else { return }
        // Whatever is on the clipboard already was copied at some unknown time, so it is left out.
        changeCount = NSPasteboard.general.changeCount
        // The pasteboard announces no changes, so look at it twice a second. That costs next to nothing.
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        timer.tolerance = 0.2
        // The common modes keep it running while a menu is open.
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func check() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount

        guard Preferences.keepsHistory,
              Preferences.savesPrivateCopies || Self.privateTypes.isDisjoint(with: pasteboard.types ?? []),
              let text = pasteboard.string(forType: .string) else { return }
        history.add(text)
    }
}
